// ============================================================
//  main.cpp — نقطة البداية: عرض عملي للـ Mini Blockchain
// ============================================================
//
//  🔗 Mini Blockchain in C++
//  ─────────────────────────
//  يعرض: إنشاء سلسلة → إضافة بلوكات → تعدين → تحقق → تزوير
//
// ============================================================

#include <iostream>
#include "blockchain.h"

int main() {
    // ═══════════════════════════════════════════════
    //  الخطوة 1: إنشاء سلسلة كتل بصعوبة 4
    //  (الهاش لازم يبدأ بـ 4 أصفار "0000...")
    // ═══════════════════════════════════════════════
    Blockchain myChain(4);

    // ═══════════════════════════════════════════════
    //  الخطوة 2: إضافة معاملات (بلوكات جديدة)
    //  كل بلوك يتم تعدينه قبل ما ينضاف للسلسلة
    // ═══════════════════════════════════════════════
    myChain.addBlock("Ahmed -> Sara : 50 BTC");
    myChain.addBlock("Sara -> Khalid : 25 BTC");
    myChain.addBlock("Khalid -> Nora : 10 BTC");

    // ═══════════════════════════════════════════════
    //  الخطوة 3: عرض السلسلة كاملة
    // ═══════════════════════════════════════════════
    myChain.printChain();

    // ═══════════════════════════════════════════════
    //  الخطوة 4: التحقق من صحة السلسلة
    // ═══════════════════════════════════════════════
    myChain.isChainValid();

    // ═══════════════════════════════════════════════
    //  الخطوة 5: محاولة تزوير! (عرض تعليمي)
    //  هنغير بيانات بلوك ونشوف هل السلسلة تكتشف
    // ═══════════════════════════════════════════════
    myChain.tamperBlock(2, "Sara -> HACKER : 999 BTC");

    // ═══════════════════════════════════════════════
    //  الخطوة 6: إعادة التحقق بعد التزوير
    //  المفروض السلسلة تكتشف التلاعب!
    // ═══════════════════════════════════════════════
    myChain.isChainValid();

    std::cout << "\n  ╔═══════════════════════════════════════════════════════════════════════╗" << std::endl;
    std::cout << "  ║                     🏁 Demo Complete!                                ║" << std::endl;
    std::cout << "  ╚═══════════════════════════════════════════════════════════════════════╝" << std::endl;
    std::cout << std::endl;

    return 0;
}
